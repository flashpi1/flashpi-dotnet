using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace Flashpi.Tools.Readme;

/// <summary>
/// Keeps every <c>csharp</c> block of both READMEs compiled: each one becomes a file of
/// <c>tests/Flashpi.Examples/Readme/</c>, which CI builds with warnings as errors.
/// </summary>
/// <remarks>
/// <para><c>readme generate</c> writes the files; <c>readme check</c> fails when they differ from the
/// READMEs. A block's <c>using</c> directives go to the top of its file; a block that declares a
/// type stays as it is, and any other becomes the body of an async method of a class that
/// derives from <c>ReadmeContext</c>, which supplies the names a block takes from an earlier one
/// (<c>flashpi</c>, <c>invoice</c>, <c>body</c>, ...).</para>
/// </remarks>
internal static partial class ReadmeCommand
{
    public const string ExamplesPath = "tests/Flashpi.Examples/Readme";

    private static readonly (string File, string Prefix)[] Readmes = [("README.md", "Es"), ("README.en.md", "En")];

    public static int Run(string root, bool check)
    {
        var expected = Generate(root);
        var directory = Path.Combine(root, ExamplesPath);
        if (check)
        {
            var current = Directory.Exists(directory)
                ? Directory.GetFiles(directory, "*.cs").ToDictionary(file => Path.GetFileName(file), File.ReadAllText, StringComparer.Ordinal)
                : [];
            var stale = expected.Where(entry => !current.TryGetValue(entry.Key, out var text) || text != entry.Value).Select(entry => entry.Key)
                .Concat(current.Keys.Where(name => !expected.ContainsKey(name)))
                .Order(StringComparer.Ordinal)
                .ToList();
            if (stale.Count > 0)
            {
                Console.Error.WriteLine(
                    $"{ExamplesPath} is out of date ({string.Join(", ", stale)}). Run: dotnet run --project tools/Flashpi.Tools -- readme generate");
                return 1;
            }
            Console.WriteLine($"{ExamplesPath} matches the READMEs");
            return 0;
        }
        if (Directory.Exists(directory))
        {
            foreach (var file in Directory.GetFiles(directory, "*.cs"))
            {
                File.Delete(file);
            }
        }
        foreach (var (name, text) in expected)
        {
            Repository.WriteText(Path.Combine(directory, name), text);
        }
        Console.WriteLine($"Wrote {expected.Count} files to {ExamplesPath}");
        return 0;
    }

    /// <summary>The example files of both READMEs, by file name.</summary>
    public static Dictionary<string, string> Generate(string root)
    {
        var files = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var (readme, prefix) in Readmes)
        {
            var blocks = Blocks(File.ReadAllText(Path.Combine(root, readme)).ReplaceLineEndings("\n"));
            for (var index = 0; index < blocks.Count; index++)
            {
                var name = string.Create(CultureInfo.InvariantCulture, $"{prefix}{index + 1:00}");
                files[$"{name}.cs"] = Example(readme, index + 1, name, blocks[index]);
            }
        }
        return files;
    }

    /// <summary>The code of every <c>```csharp</c> block, in order.</summary>
    public static List<string> Blocks(string markdown) =>
        [.. CSharpBlock().Matches(markdown).Select(match => match.Groups[1].Value)];

    private static string Example(string readme, int number, string name, string block)
    {
        var lines = block.TrimEnd('\n').Split('\n');
        var usings = lines.TakeWhile(line => UsingDirective().IsMatch(line) || line.Length == 0).ToList();
        var code = lines.Skip(usings.Count).ToList();
        var output = new StringBuilder();
        output.Append(CultureInfo.InvariantCulture, $"""
            // <auto-generated/>
            // GENERATED by tools/Flashpi.Tools from {readme} (C# block {number}). Do not edit by hand: change
            // the README, then run `dotnet run --project tools/Flashpi.Tools -- readme generate`.
            #nullable enable

            """);
        foreach (var directive in usings.Where(line => line.Length > 0))
        {
            output.Append(directive).Append('\n');
        }
        output.Append("using Flashpi.Examples;\n\n");
        output.Append(CultureInfo.InvariantCulture, $"namespace Flashpi.Examples.Readme.{name};\n\n");
        var first = code.FirstOrDefault(line => line.Length > 0 && !line.StartsWith("//", StringComparison.Ordinal)) ?? "";
        if (TypeDeclaration().IsMatch(first))
        {
            foreach (var line in code)
            {
                output.Append(line).Append('\n');
            }
            return output.ToString();
        }
        output.Append("internal sealed class Example : ReadmeContext\n{\n");
        output.Append("    public async Task RunAsync()\n    {\n");
        foreach (var line in code)
        {
            output.Append(line.Length == 0 ? "" : "        " + line).Append('\n');
        }
        output.Append("    }\n}\n");
        return output.ToString();
    }

    [GeneratedRegex("^```csharp\\n(.*?)^```$", RegexOptions.Multiline | RegexOptions.Singleline)]
    private static partial Regex CSharpBlock();

    [GeneratedRegex("^using (static )?[A-Za-z0-9_.]+( = [A-Za-z0-9_.<>]+)?;$")]
    private static partial Regex UsingDirective();

    [GeneratedRegex("^(\\[|public |internal |namespace |sealed |static |file )")]
    private static partial Regex TypeDeclaration();
}
